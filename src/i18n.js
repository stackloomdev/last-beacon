let language = 'zh';
export const getLanguage = () => language;
export function setLanguage(next) {
  if (!LANGUAGES.includes(next)) return false;
  language = next;
  return true;
}
export function resolveLanguage(saved, preferences = []) {
  if (LANGUAGES.includes(saved)) return saved;
  for (const preference of preferences) {
    const base = String(preference).toLowerCase().split(/[-_]/)[0];
    if (LANGUAGES.includes(base)) return base;
  }
  return 'zh';
}
export function preferredLanguage(storage, preferences) {
  let saved;
  try { saved = storage?.getItem(LANGUAGE_KEY); } catch {}
  return resolveLanguage(saved, preferences);
}
export function saveLanguage(storage) {
  try { storage?.setItem(LANGUAGE_KEY, language); } catch {}
}
export function t(key, params = {}, locale = language) {
  const text = messages[key]?.[locale === 'en' ? 1 : 0];
  if (text === undefined) throw new Error(`Missing translation: ${key}`);
  return text.replace(/\{(\w+)\}/g, (token, name) => params[name] ?? token);
}
export const towerName = type => t(`tower.${type}.name`);
